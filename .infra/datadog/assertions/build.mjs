import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { escapePackedTable } from './safe-packed-table.mjs';
import { compactTokenizerPlugin } from './compact-tokenizer.mjs';

const directory = path.dirname(fileURLToPath(import.meta.url));
const runtimeLicenses = await Promise.all(['parse5', 'entities'].map(async name => {
  const pkg = JSON.parse(await readFile(path.join(directory, 'node_modules', name, 'package.json'), 'utf8'));
  const license = await readFile(path.join(directory, 'node_modules', name, 'LICENSE'), 'utf8');
  return name + ' ' + pkg.version + ' (' + pkg.license + ')\n' + license;
}));
const banner = '/*!\nStandalone Datadog vanity assertion; generated by npm run build.\n' + runtimeLicenses.join('\n\n') + '\n*/';
// This reviewed list names only properties owned by the closed tokenizer,
// decoder and handler graph. Datadog APIs, baseline keys and native methods
// retain their names. Quoted keys (including entity dictionaries) are untouched.
const mangleCache = JSON.parse(await readFile(path.join(directory, 'mangle-properties.json'), 'utf8'));
const mangleProps = new RegExp('^(?:' + Object.keys(mangleCache).join('|') + ')$');
const output = await build({
  absWorkingDir: directory,
  entryPoints: ['vanity.mjs'],
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  target: 'es2018',
  tsconfigRaw: { compilerOptions: { useDefineForClassFields: false } },
  minify: true,
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: banner },
  mangleProps,
  mangleCache,
  mangleQuoted: false,
  plugins: [compactTokenizerPlugin(directory)],
  metafile: true,
  write: false,
});
const packedTable = await readFile(path.join(directory, 'node_modules/entities/dist/generated/decode-data-html.js'), 'utf8');
const text = escapePackedTable(output.outputFiles[0].text, packedTable);
if (text.split('__EXPECTED_METADATA__').length !== 2) throw new Error('Expected exactly one Terraform metadata marker');
if (Object.values(output.metafile.outputs).some(file => file.imports.length !== 0)) throw new Error('Runtime dependency leaked into assertion bundle');
const baseline = JSON.parse(await readFile(path.resolve(directory, '../../../.tools/vanity/internal/vanity/baseline.json'), 'utf8'));
const mergo = baseline.find(route => route.path === '/mergo/');
if (!mergo) throw new Error('Reviewed Mergo baseline is missing');
const metadata = [...baseline, { ...mergo, go_import: ['dario.cat/mergo git https://example.invalid/notification-probe'] }];
const maxInjectedBytes = Math.max(...metadata.map(route => Buffer.byteLength(text.replace('__EXPECTED_METADATA__', () => JSON.stringify(route)), 'utf8')));
if (maxInjectedBytes > 49_000) throw new Error('Injected assertion exceeds the reviewed 49,000-byte budget');
const filename = path.join(directory, 'vanity.js');
if (process.argv.includes('--check')) {
  if (await readFile(filename, 'utf8') !== text) throw new Error('Committed vanity.js is stale; run npm run build');
} else {
  await writeFile(filename, text);
}
console.log('vanity.js: ' + Buffer.byteLength(text, 'utf8') + ' UTF-8 bytes; maximum injected assertion: ' + maxInjectedBytes);
